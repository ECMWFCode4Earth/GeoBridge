"""
geobridge.modules.extract
~~~~~~~~~~~~~~~~~~~~~~~~~

Extract spatial and temporal subsets from Copernicus ARCO Zarr stores
and write them as Cloud Optimized GeoTIFF (COG) files.

The module is designed against the live ECMWF ARCO Data Lake at
``arco.datastores.ecmwf.int`` (verified 2026-05-05).

Two Zarr archive flavours exist for each dataset and the right one is
picked automatically:

- **time_chunked** — chunked along the time axis. Use for spatial maps
  over short periods (the typical GIS use case).
- **geo_chunked** — chunked along the spatial axes. Use for long time
  series at a single point.

Requires the ``[zarr]`` optional dependencies::

    pip install "geobridge[zarr]"
"""

from __future__ import annotations

import logging
import os
from datetime import datetime
from functools import lru_cache
from pathlib import Path
from typing import Optional, Union

from geobridge.auth import auth_header, is_authenticated

logger = logging.getLogger(__name__)

DateLike = Union[str, datetime]
PathLike = Union[str, os.PathLike]

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

_OVERRIDES_PATH = (
    Path(__file__).parent.parent / "semantic" / "arco_overrides.yaml"
)
_ARCO_SNAPSHOT_PATH = (
    Path(__file__).parent.parent / "semantic" / "arco_snapshot.yaml"
)
_CDS_SNAPSHOT_PATH = (
    Path(__file__).parent.parent / "semantic" / "cds_snapshot.yaml"
)

# Aggregations supported. Maps user-friendly name → (pandas resample freq, op).
_AGGREGATIONS: dict[str, Optional[tuple[str, str]]] = {
    "raw": None,                      # No aggregation — write all timesteps
    "daily_mean": ("D", "mean"),
    "daily_max": ("D", "max"),
    "daily_min": ("D", "min"),
    "monthly_mean": ("MS", "mean"),
    "monthly_max": ("MS", "max"),
    "monthly_min": ("MS", "min"),
    "annual_mean": ("YS", "mean"),
    "annual_max": ("YS", "max"),
}

# Heuristic for picking time_chunked vs geo_chunked.  When the user asks for
# more than this many days at a single point, the geo_chunked store is faster.
_GEO_CHUNK_THRESHOLD_DAYS = 90


# ---------------------------------------------------------------------------
# Exceptions
# ---------------------------------------------------------------------------

class ExtractionError(RuntimeError):
    """Raised when Zarr extraction or GeoTIFF writing fails."""


# ---------------------------------------------------------------------------
# Lazy imports for optional heavy dependencies
# ---------------------------------------------------------------------------

def _require_xarray():
    """Import xarray and rioxarray on demand."""
    try:
        import xarray as xr
        import rioxarray  # noqa: F401  (registers the .rio accessor)
        import numpy as np
        return xr, np
    except ImportError as exc:
        raise ExtractionError(
            "zarr_to_geotiff() requires the [zarr] extras. Install with:\n"
            "    pip install 'geobridge[zarr]'"
        ) from exc


