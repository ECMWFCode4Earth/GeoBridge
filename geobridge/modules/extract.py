def _pick_chunking(entry: dict, time_range: tuple, bbox: tuple) -> str:
    """Choose time_chunked vs geo_chunked based on the request shape."""
    # If only one is available, no choice.
    zarr_urls = entry.get("zarr", {})
    if "time_chunked" in zarr_urls and "geo_chunked" not in zarr_urls:
        return "time_chunked"
    if "geo_chunked" in zarr_urls and "time_chunked" not in zarr_urls:
        return "geo_chunked"

    # Compute approximate request shape
    t_start, t_end = time_range
    if isinstance(t_start, str):
        t_start = datetime.fromisoformat(t_start.replace("Z", "+00:00")
                                         if "T" in t_start else t_start)
    if isinstance(t_end, str):
        t_end = datetime.fromisoformat(t_end.replace("Z", "+00:00")
                                       if "T" in t_end else t_end)
    n_days = max((t_end - t_start).days, 1)

    west, south, east, north = bbox
    bbox_area_deg2 = max((east - west) * (north - south), 0.0001)

    # Heuristic: tiny bbox + long time → geo_chunked; otherwise time_chunked
    if bbox_area_deg2 < 1.0 and n_days > _GEO_CHUNK_THRESHOLD_DAYS:
        return "geo_chunked"
    return "time_chunked"


def _open_arco_zarr(zarr_url: str):
    """Open an ARCO Zarr store with bearer-token auth."""
    xr, _ = _require_xarray()

    if not is_authenticated():
        raise ExtractionError(
            "Not authenticated. Call geobridge.authenticate() before "
            "calling zarr_to_geotiff()."
        )

    storage_options = {"headers": auth_header()}
    logger.debug("Opening ARCO Zarr store at %s", zarr_url)
    try:
        return xr.open_zarr(
            zarr_url,
            consolidated=True,
            storage_options=storage_options,
            chunks="auto",
        )
    except Exception as exc:
        raise ExtractionError(
            f"Failed to open ARCO Zarr store {zarr_url}: {exc}\n\n"
            "Common causes:\n"
            "  - Your CDS API key is invalid or expired\n"
            "  - You haven't accepted the dataset licence on the CDS portal\n"
            "  - The ARCO service is rate-limiting you (try again later)\n"
            "  - The Zarr URL has changed (check arco_overrides.yaml)"
        ) from exc


