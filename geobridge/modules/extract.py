def list_datasets() -> list[str]:
    """Return the IDs of all datasets supported for extraction.

    "Supported" means the dataset is present in the ARCO catalogue
    snapshot (which is auto-generated from ECMWF's STAC catalogue at
    arco.datastores.ecmwf.int).  All 27 datasets in the ARCO data lake
    are wired up automatically — no per-dataset code changes needed.

    Examples
    --------
    >>> import geobridge as gb
    >>> for dsid in gb.list_datasets():
    ...     print(dsid)
    """
    snapshot = _load_arco_snapshot()
    if snapshot:
        return sorted(snapshot.keys())
    # Fallback if the snapshot file is missing
    return sorted(_load_overrides().keys())


def list_variables(dataset_id: str, subset: Optional[str] = None) -> list[str]:
    """Return the variable short names available for a dataset.

    Reads the variable list directly from the ARCO catalogue snapshot.
    Variable names are returned in their ARCO short form (e.g. ``t2m``,
    ``pm2p5``, ``utci``) — the form actually used inside the Zarr store.
    Either short or long names can be passed to :func:`zarr_to_geotiff`.

    Parameters
    ----------
    dataset_id : str
        ARCO catalogue id, e.g. ``reanalysis_era5_single_levels``.
    subset : str, optional
        Specific subset (e.g. ``sfc``).  Defaults to the primary subset.

    Examples
    --------
    >>> gb.list_variables("reanalysis_era5_single_levels")
    ['blh', 'cbh', 'd2m', ..., 't2m', 'tp', ...]
    """
    entry = _get_dataset_entry(dataset_id, subset=subset)
    # Prefer the actual variable list captured from the ARCO snapshot
    var_meta = entry.get("variables_meta") or {}
    if var_meta:
        return sorted(var_meta.keys())
    # Fall back to alias keys
    return list(entry.get("variable_aliases", {}).keys())


def zarr_to_geotiff(
    dataset: str,
    variable: str,
    bbox: tuple[float, float, float, float],
    time_range: tuple[DateLike, DateLike],
    aggregation: str = "raw",
    output_path: Optional[PathLike] = None,
    cog: bool = True,
    target_crs: Optional[str] = None,
    chunking: Optional[str] = None,
) -> Path:
    """Extract a subset of an ARCO Zarr store as a GeoTIFF.

    Parameters
    ----------
    dataset : str
        Dataset identifier, e.g. ``'reanalysis-era5-single-levels'``.
        Must be present in the GeoBridge ARCO catalogue.
    variable : str
        Variable name in either CDS long form (``'2m_temperature'``) or
        ARCO short form (``'t2m'``).
    bbox : tuple
        Spatial extent as ``(west, south, east, north)`` in WGS-84 degrees.
    time_range : tuple
        ``(start, end)`` — either ISO-8601 date strings or datetime objects.
    aggregation : str
        Temporal aggregation to apply before writing.  One of:
        ``'raw'``, ``'daily_mean'``, ``'daily_max'``, ``'daily_min'``,
        ``'monthly_mean'``, ``'monthly_max'``, ``'monthly_min'``,
        ``'annual_mean'``, ``'annual_max'``.
    output_path : path-like, optional
        Destination file. Defaults to
        ``./{dataset}_{variable}_{aggregation}.tif`` in the current directory.
    cog : bool
        If True (default) write a Cloud Optimized GeoTIFF.
    target_crs : str, optional
        Reproject to this CRS, e.g. ``'EPSG:3857'``.
        Default keeps the native EPSG:4326.
    chunking : {'time_chunked', 'geo_chunked'}, optional
        Force a specific chunking flavour.  Default is to auto-pick based
        on the request shape.

    Returns
    -------
    Path
        Path to the written GeoTIFF.

    Raises
    ------
    ExtractionError
        If the dataset, variable, authentication, or write step fails.

    Examples
    --------
    >>> import geobridge as gb
    >>> gb.authenticate()
    >>> tif = gb.zarr_to_geotiff(
    ...     dataset="reanalysis-era5-single-levels",
    ...     variable="2m_temperature",
    ...     bbox=(23.0, 37.5, 24.5, 38.5),
    ...     time_range=("2023-07-01", "2023-07-31"),
    ...     aggregation="monthly_mean",
    ...     cog=True,
    ... )
    >>> print(tif)
    """
    xr, _ = _require_xarray()

    # 1. Catalogue lookup
    entry = _get_dataset_entry(dataset)
    short_var = _resolve_variable_name(entry, variable)

    # 2. Pick chunking flavour and Zarr URL
    flavour = chunking or _pick_chunking(entry, time_range, bbox)
    zarr_urls = entry.get("zarr", {})
    if flavour not in zarr_urls:
        raise ExtractionError(
            f"Chunking flavour {flavour!r} not available for dataset "
            f"{dataset!r}.  Available: {list(zarr_urls)}"
        )
    zarr_url = zarr_urls[flavour]
    logger.info("Using %s archive for %s", flavour, dataset)

    # 3. Open the store
    ds = _open_arco_zarr(zarr_url)

    # 4. Subset
    da, coord_names = _select_subset(ds, short_var, bbox, time_range, entry)

    # 5. Aggregate
    da = _aggregate(da, aggregation, coord_names["time"])

    # 6. Attach CRS
    da = _ensure_crs(da, coord_names["lon"], coord_names["lat"])

    # 7. Optional reprojection
    if target_crs and target_crs.upper() != "EPSG:4326":
        try:
            da = da.rio.reproject(target_crs)
        except Exception as exc:
            raise ExtractionError(
                f"Reprojection to {target_crs} failed: {exc}"
            ) from exc

    # 8. Write
    if output_path is None:
        safe_dataset = dataset.replace("/", "_")
        output_path = (Path.cwd() /
                       f"{safe_dataset}_{short_var}_{aggregation}.tif")
    output_path = Path(output_path)

    try:
        return _write_geotiff(da, output_path, cog)
    except Exception as exc:
        raise ExtractionError(
            f"Failed to write GeoTIFF to {output_path}: {exc}"
        ) from exc
