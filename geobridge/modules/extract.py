def _coord_name(da, candidates: tuple[str, ...]) -> Optional[str]:
    """Return the first coordinate name from *candidates* present on *da*."""
    return next((c for c in candidates if c in da.coords), None)


def _select_subset(ds, variable: str, bbox: tuple, time_range: tuple,
                   entry: dict):
    """Apply spatial and temporal subsetting to an xarray Dataset.

    Returns
    -------
    da : xarray.DataArray
        The subsetted variable.
    coord_names : dict
        Names of the coordinate axes in the returned DataArray
        (``lon``, ``lat``, ``time``).
    """
    # Look up the variable in the dataset
    if variable not in ds.data_vars:
        available = list(ds.data_vars)[:20]
        raise ExtractionError(
            f"Variable {variable!r} not in Zarr store. "
            f"First 20 available variables: {available}"
        )
    da = ds[variable]

    # Coordinate names vary by dataset
    lon_name = _coord_name(da, ("longitude", "lon", "x"))
    lat_name = _coord_name(da, ("latitude", "lat", "y"))
    time_name = _coord_name(da, ("time", "valid_time", "t"))
    if lon_name is None or lat_name is None:
        raise ExtractionError(
            "Could not find longitude/latitude coordinates. "
            f"Available coords: {list(da.coords)}"
        )

    west, south, east, north = bbox

    # Handle 0–360 longitude convention if the dataset uses it
    if entry.get("longitude_convention") == "zero_to_360":
        if west < 0:
            west += 360
        if east < 0:
            east += 360
        if west > east:
            west, east = east, west

    # Latitude direction depends on the dataset
    lat_values = da[lat_name].values
    lat_ascending = bool(lat_values[0] < lat_values[-1])
    lat_slice = slice(south, north) if lat_ascending else slice(north, south)

    da = da.sel({lon_name: slice(west, east), lat_name: lat_slice})

    if time_name is not None:
        t_start, t_end = time_range
        da = da.sel({time_name: slice(t_start, t_end)})

    if 0 in da.sizes.values():
        raise ExtractionError(
            f"Subsetting returned an empty array for variable {variable!r}.\n"
            f"  bbox = {bbox}\n"
            f"  time_range = {time_range}\n"
            f"  resulting shape = {dict(da.sizes)}\n\n"
            "Likely causes:\n"
            "  - bbox too small to contain any grid cells "
            f"(grid is ~{entry.get('native_resolution_deg', '?')}° spaced)\n"
            "  - time_range outside dataset coverage "
            f"({entry.get('time_range', {})})"
        )

    return da, {"lon": lon_name, "lat": lat_name, "time": time_name}


def _aggregate(da, aggregation: str, time_name: Optional[str]):
    """Apply temporal aggregation if requested."""
    if aggregation == "raw" or time_name is None:
        return da
    if aggregation not in _AGGREGATIONS:
        raise ExtractionError(
            f"Unknown aggregation {aggregation!r}. "
            f"Valid options: {list(_AGGREGATIONS)}"
        )
    spec = _AGGREGATIONS[aggregation]
    if spec is None:
        return da
    freq, op = spec
    return getattr(da.resample({time_name: freq}), op)()


def _ensure_crs(da, lon_name: str, lat_name: str):
    """Rename to standard x/y dims and attach a CRS for rioxarray export.

    Also ensures the y-axis is descending (north-up) which prevents
    the 'NotGeoreferencedWarning' from rasterio when the affine
    transform appears to be identity.
    """
    rename_map = {}
    if lon_name != "x":
        rename_map[lon_name] = "x"
    if lat_name != "y":
        rename_map[lat_name] = "y"
    if rename_map:
        da = da.rename(rename_map)

    # Ensure y-axis is descending (north at top) — rioxarray needs this
    # to compute a valid geotransform
    y_vals = da.coords["y"].values
    if len(y_vals) > 1 and y_vals[0] < y_vals[-1]:
        da = da.sortby("y", ascending=False)

    da = da.rio.set_spatial_dims(x_dim="x", y_dim="y", inplace=False)
    if da.rio.crs is None:
        da = da.rio.write_crs("EPSG:4326")

    # Force rioxarray to recompute the transform from the coordinate arrays
    # This prevents the identity-transform warning
    da.encoding.pop("transform", None)

    return da


def _write_geotiff(da, output_path: Path, cog: bool) -> Path:
    """Write a DataArray to GeoTIFF (optionally Cloud Optimized)."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    if cog:
        da.rio.to_raster(
            output_path, driver="COG",
            compress="DEFLATE", BLOCKSIZE=512,
        )
    else:
        da.rio.to_raster(
            output_path, driver="GTiff",
            compress="DEFLATE", tiled=True,
        )
    return output_path


