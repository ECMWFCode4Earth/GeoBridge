@lru_cache(maxsize=1)
def _load_arco_snapshot() -> dict:
    """Load and cache the ARCO catalogue snapshot.

    The snapshot is generated by ``scripts/refresh_arco_catalogue.py`` and
    contains, for every ARCO-available dataset, the Zarr URLs, variable
    list with units and value ranges, dimensions, and optional WMTS
    endpoint — all sourced directly from ECMWF's own STAC catalogue at
    ``arco.datastores.ecmwf.int``.

    Returns an empty dict when the snapshot file is missing.  Extraction
    still works for any dataset present in ``arco_overrides.yaml``.
    """
    try:
        import yaml
    except ImportError as exc:
        raise ExtractionError(
            "PyYAML is required. Install with: pip install pyyaml"
        ) from exc

    if not _ARCO_SNAPSHOT_PATH.exists():
        logger.warning(
            "ARCO catalogue snapshot not found at %s. "
            "Run scripts/refresh_arco_catalogue.py to generate it. "
            "Extraction will still work for datasets in arco_overrides.yaml.",
            _ARCO_SNAPSHOT_PATH,
        )
        return {}
    with _ARCO_SNAPSHOT_PATH.open(encoding="utf-8") as fp:
        data = yaml.safe_load(fp) or {}
    return data.get("datasets", {}) or {}


@lru_cache(maxsize=1)
def _load_overrides() -> dict:
    """Load and cache the slim ARCO overrides file.

    The overrides file holds only the CDS-to-ARCO variable name alias
    mapping (CDS long form like ``2m_temperature`` to ARCO short form
    like ``t2m``).  Since v0.2 everything else is auto-derived from the
    ARCO STAC catalogue snapshot.
    """
    try:
        import yaml
    except ImportError as exc:
        raise ExtractionError(
            "PyYAML is required. Install with: pip install pyyaml"
        ) from exc

    if not _OVERRIDES_PATH.exists():
        logger.warning(
            "Variable alias overrides not found at %s", _OVERRIDES_PATH,
        )
        return {}
    with _OVERRIDES_PATH.open(encoding="utf-8") as fp:
        data = yaml.safe_load(fp) or {}
    return data.get("overrides", {}) or {}


@lru_cache(maxsize=1)
def _load_cds_snapshot() -> dict:
    """Load and cache the CDS catalogue snapshot (auxiliary, optional)."""
    try:
        import yaml
    except ImportError:
        return {}
    if not _CDS_SNAPSHOT_PATH.exists():
        return {}
    with _CDS_SNAPSHOT_PATH.open(encoding="utf-8") as fp:
        data = yaml.safe_load(fp) or {}
    return data.get("datasets", {}) or {}


def _pick_default_subset(dataset_entry: dict) -> Optional[str]:
    """Pick a sensible default subset id for a dataset.

    Preference: a subset whose id is in {sfc, all, surface} (typical primary
    subset names in the ARCO catalogue), else the first one in alphabetical
    order so behaviour is deterministic.
    """
    subsets = dataset_entry.get("subsets", {}) or {}
    if not subsets:
        return None
    for preferred in ("sfc", "all", "surface"):
        if preferred in subsets:
            return preferred
    return sorted(subsets)[0]


def _normalise_zarr_keys(zarr_block: dict) -> dict:
    """Convert ARCO snapshot camelCase keys to the extract module's snake_case.

    ECMWF's STAC uses ``timeChunked`` / ``geoChunked`` / ``downsampled4``.
    The rest of extract.py reads ``time_chunked`` / ``geo_chunked``.
    Translation happens here once.
    """
    out: dict[str, str] = {}
    for key, url in (zarr_block or {}).items():
        if not url:
            continue
        if key == "timeChunked":
            out["time_chunked"] = url
        elif key == "geoChunked":
            out["geo_chunked"] = url
        elif key.startswith("downsampled"):
            # Keep downsampled variants under the same key for now
            out[key] = url
        else:
            out[key] = url
    return out


def _get_dataset_entry(dataset_id: str, subset: Optional[str] = None) -> dict:
    """Look up access details for *dataset_id*, with helpful errors on miss.

    Builds the entry dict the rest of extract.py expects.  Primary source
    is the auto-generated ARCO snapshot (``arco_snapshot.yaml``);
    variable aliases come from the small ``arco_overrides.yaml``.  CDS
    snapshot metadata is attached under ``_cds`` for informational use.

    Parameters
    ----------
    dataset_id : str
        ARCO catalogue id, e.g. ``reanalysis_era5_single_levels``.
        Hyphens in CDS-style ids (``reanalysis-era5-single-levels``)
        are converted to underscores transparently.
    subset : str, optional
        Subset within the dataset (e.g. ``sfc`` for ERA5 single levels).
        Defaults to a sensible primary subset.
    """
    # CDS-style ids use hyphens; ARCO uses underscores. Accept either.
    canonical_id = dataset_id.replace("-", "_")
    arco = _load_arco_snapshot()
    overrides = _load_overrides()

    if canonical_id not in arco:
        # Fall back to slim overrides keyed by the CDS-style id
        if dataset_id in overrides and "zarr" in overrides[dataset_id]:
            return dict(overrides[dataset_id])
        available = sorted(arco.keys())
        raise ExtractionError(
            f"Dataset {dataset_id!r} not in the ARCO catalogue snapshot.\n"
            f"Datasets currently available for extraction: {available[:10]}"
            f"{' ...' if len(available) > 10 else ''}\n\n"
            "To refresh the snapshot:\n"
            "    python scripts/refresh_arco_catalogue.py\n\n"
            "If the dataset is genuinely not in ARCO, it can only be "
            "accessed via the legacy CDS download API (cdsapi)."
        )

    dataset_entry = arco[canonical_id]
    subsets = dataset_entry.get("subsets", {}) or {}
    chosen = subset or _pick_default_subset(dataset_entry)
    if chosen is None or chosen not in subsets:
        available_subsets = sorted(subsets)
        raise ExtractionError(
            f"Dataset {dataset_id!r} has no subset {chosen!r}.\n"
            f"Available subsets: {available_subsets}"
        )

    subset_entry = subsets[chosen]

    # Build the entry shape the rest of extract.py expects
    entry: dict[str, Any] = {
        "dataset_id": canonical_id,
        "subset_id": chosen,
        "service": dataset_entry.get("service", "C3S"),
        "title": dataset_entry.get("title", canonical_id),
        "zarr": _normalise_zarr_keys(subset_entry.get("zarr", {})),
        "wmts_url": subset_entry.get("wmts") or "",
        "bbox": subset_entry.get("bbox"),
        "time_start": subset_entry.get("time_start"),
        "time_end": subset_entry.get("time_end"),
        "dimensions": subset_entry.get("dimensions", {}),
        "variables_meta": subset_entry.get("variables", {}),
    }

    # Derive native resolution from the latitude step if available
    lat_dim = subset_entry.get("dimensions", {}).get("latitude") or {}
    if "step" in lat_dim:
        entry["native_resolution_deg"] = float(lat_dim["step"])

    # Derive latitude direction from the extent
    lat_extent = lat_dim.get("extent")
    if lat_extent and len(lat_extent) == 2 and lat_extent[0] is not None:
        entry["coordinate_order"] = (
            "lat_ascending" if lat_extent[0] < lat_extent[1] else "lat_descending"
        )

    # Derive longitude convention from the extent
    lon_dim = subset_entry.get("dimensions", {}).get("longitude") or {}
    lon_extent = lon_dim.get("extent")
    if lon_extent and len(lon_extent) == 2 and lon_extent[0] is not None:
        entry["longitude_convention"] = (
            "minus180_to_180" if lon_extent[0] < 0 else "zero_to_360"
        )

    # Variable aliases come from the slim overrides file (CDS long to ARCO short)
    aliases_top = overrides.get("variable_aliases", {}) or {}
    aliases_per_dataset = (overrides.get(canonical_id) or {}).get(
        "variable_aliases", {}
    )
    entry["variable_aliases"] = {**aliases_top, **aliases_per_dataset}

    # Attach CDS STAC metadata if it happens to be available
    cds = _load_cds_snapshot()
    # CDS catalogue uses hyphenated ids
    cds_id = dataset_id.replace("_", "-")
    if cds_id in cds:
        entry["_cds"] = cds[cds_id]

    return entry


def _resolve_variable_name(entry: dict, variable: str) -> str:
    """Translate a CDS-style variable name to the ARCO short name."""
    aliases = entry.get("variable_aliases", {})
    # If it is already a short name (i.e. value of an alias), leave it
    if variable in aliases.values():
        return variable
    # Translate from the long form
    if variable in aliases:
        return aliases[variable]
    # Unknown — let xarray raise a clear KeyError later
    return variable


